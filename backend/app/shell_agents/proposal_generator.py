"""Deterministic proposal generator."""

from __future__ import annotations

import logging
from typing import Any

from app.database.models import Project
from app.database.schemas import ProjectEstimate, ProjectScope

logger = logging.getLogger(__name__)


class ProposalGeneratorAgent:
    """Renders a human-readable proposal from scope + estimate."""

    async def generate(
        self,
        project: Project,
        scope: ProjectScope | dict[str, Any],
        estimate: ProjectEstimate | dict[str, Any],
    ) -> str:
        if hasattr(scope, "model_dump"):
            s = scope.model_dump()
        else:
            s = scope
        if hasattr(estimate, "model_dump"):
            e = estimate.model_dump()
        else:
            e = estimate

        features_md = "\n".join(
            f"- **{f.get('name', f) if isinstance(f, dict) else getattr(f, 'name', str(f))}**: "
            f"{f.get('description', '') if isinstance(f, dict) else getattr(f, 'description', '')}"
            for f in (s.get("features") or [])
        )

        md = f"""# Project Proposal: {project.title}

## Summary
{s.get("summary", "")}

## Scope

### Features
{features_md or "_No features listed_"}

### Assumptions
{chr(10).join("- " + a for a in (s.get("assumptions") or [])) or "_None_"}

### Constraints
{chr(10).join("- " + c for c in (s.get("constraints") or [])) or "_None_"}

### Out of Scope
{chr(10).join("- " + o for o in (s.get("out_of_scope") or [])) or "_None_"}

## Timeline
Approximately **{s.get("timeline_weeks", "TBD")} weeks**.

## Estimate
- **Total effort**: {e.get("total_hours", "?")} hours
- **Estimated cost**: {e.get("currency", "USD")} {e.get("total_cost", "?")}
- **Confidence**: {e.get("confidence", "medium")}

### Breakdown
{chr(10).join(f"- {k}: {v}h" for k, v in (e.get("breakdown") or {}).items())}

---
*Generated by ScopePilot AI*
"""
        return md
